-- Equivalente Postgres. As razões estão comentadas no arquivo SQLite; a
-- única diferença é a chave estrangeira em monitor.group_id, que aqui
-- existe porque o PostgreSQL sabe removê-la no Down.
CREATE TABLE monitor_group (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT   NOT NULL,
    slug       TEXT   NOT NULL,
    parent_id  BIGINT          REFERENCES monitor_group (id),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE UNIQUE INDEX idx_monitor_group_slug ON monitor_group (COALESCE(parent_id, 0), slug);
CREATE UNIQUE INDEX idx_monitor_group_name ON monitor_group (COALESCE(parent_id, 0), name);

ALTER TABLE monitor ADD COLUMN group_id BIGINT REFERENCES monitor_group (id);
CREATE INDEX idx_monitor_group ON monitor (group_id);

DROP INDEX idx_monitor_name;
CREATE UNIQUE INDEX idx_monitor_name_in_group ON monitor (COALESCE(group_id, 0), name);

ALTER TABLE app_user ADD COLUMN all_groups INTEGER NOT NULL DEFAULT 1;

CREATE TABLE user_group (
    user_id  BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES monitor_group (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, group_id)
);

CREATE TABLE group_channel (
    group_id   BIGINT NOT NULL REFERENCES monitor_group (id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES notification_channel (id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, channel_id)
);

CREATE TABLE state_transition (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id  BIGINT NOT NULL REFERENCES monitor (id) ON DELETE CASCADE,
    from_status TEXT   NOT NULL,
    to_status   TEXT   NOT NULL,
    at          BIGINT NOT NULL,
    cause       TEXT   NOT NULL DEFAULT ''
);

CREATE INDEX idx_state_transition_monitor ON state_transition (monitor_id, at);

-- O mesmo semeio do SQLite, pela mesma razão: o monitor já fora do ar
-- ganha a mudança que o levou até ali.
INSERT INTO state_transition (monitor_id, from_status, to_status, at, cause)
SELECT s.monitor_id, 'unknown', s.status, s.since,
       COALESCE((SELECT i.cause FROM incident i
                 WHERE i.monitor_id = s.monitor_id AND i.resolved_at IS NULL
                 ORDER BY i.started_at DESC LIMIT 1), '')
FROM monitor_state s
WHERE s.status IN ('down', 'degraded') AND s.since > 0;

