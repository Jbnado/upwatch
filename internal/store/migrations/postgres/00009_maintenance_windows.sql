CREATE TABLE maintenance_window (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT   NOT NULL,
    message    TEXT   NOT NULL DEFAULT '',
    starts_at  BIGINT NOT NULL,
    ends_at    BIGINT NOT NULL,
    recurrence TEXT   NOT NULL DEFAULT 'none',
    time_zone  TEXT   NOT NULL DEFAULT 'UTC',
    ended_at   BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE maintenance_monitor (
    window_id  BIGINT NOT NULL REFERENCES maintenance_window (id) ON DELETE CASCADE,
    monitor_id BIGINT NOT NULL REFERENCES monitor (id) ON DELETE CASCADE,
    PRIMARY KEY (window_id, monitor_id)
);

CREATE TABLE maintenance_group (
    window_id BIGINT NOT NULL REFERENCES maintenance_window (id) ON DELETE CASCADE,
    group_id  BIGINT NOT NULL REFERENCES monitor_group (id) ON DELETE CASCADE,
    PRIMARY KEY (window_id, group_id)
);

